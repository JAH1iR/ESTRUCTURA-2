// operadores de asignación, incremento y decremento
let a = 1;
document.writeln('Valor de a: ', a);
document.writeln('<br>');
a++; // aumenta el valor de a en 1
document.writeln('Valor de a: ', a);
document.writeln('<br>');
a+=5; // aumento variable
document.writeln('Valor de a: ', a);
document.writeln('<br>');
a--; // resta valor en 1
document.writeln('Valor de : ',a);
document.writeln('<br>');
a-=3; // resta variable
document.writeln('Valor de a: ', a);
document.writeln('<br>');
a*=5; // multiplica variable
document.writeln('Valor de a: ',a);
document.writeln('<br>');
a/=3; // divide variable
document.writeln('Valor de a: ',a);
document.writeln('<br>');
a**=2;
document.writeln('Valor de a: ', a);