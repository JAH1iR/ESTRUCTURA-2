// operadores de comparación
let valor1, valor2
valor1 = 20;
valor2 = 10;
document.writeln(valor1 > valor2); // valor1 es mayor a valor2
document.writeln('<br>');
document.writeln(valor1 < valor2); // valor1 es menor a valor2
document.writeln('<br>');
document.writeln(valor1 == valor2); // valor1 igual a valor2
document.writeln('<br>');
document.writeln(valor1 != valor2); // valor1 es diferente a valor2
document.writeln('<br>');
document.writeln(valor1 <= valor2); // valor1 es menor o igual a valor2
document.writeln('<br>');
document.writeln(valor1 >= valor2); // valor1 es mayor o igual a valor2