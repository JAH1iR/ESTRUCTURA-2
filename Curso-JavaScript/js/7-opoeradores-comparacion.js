 // --- OPERADORES DE COMPARACIÓN ---
 // Estos operadores evalúan la relación entre dos valores y devuelven un resultado booleano: true o false.

 let valor1 = 20;
 let valor2 = 10;

 document.writeln(`<strong> Valores de comparación:</strong> valor1 = ${valor1}, valor2 = ${valor2} <br><br>`);

 // Mayor que (>)
 document.writeln(`¿Es ${valor1} mayor que ${valor2}? : ${valor1 > valor2} <br>`);

 // Menor que (<)
 document.writeln(`¿Es ${valor1} menor que ${valor2}? : ${valor1 < valor2} <br>`);

 // Igualdad (==)
 document.writeln(`¿Es ${valor1} igual a ${valor2}? : ${valor1 == valor2} <br>`);

 // Diferencia (!=)
 document.writeln(`¿Es ${valor1} diferente a ${valor2}? : ${valor1 != valor2} <br>`);

 // Menor o igual (<=)
 document.writeln(`¿Es ${valor1} menor o igual a ${valor2}? : ${valor1 <= valor2} <br>`);

 // Mayor o igual (>=)
 document.writeln(`¿Es ${valor1} mayor o igual a ${valor2}? : ${valor1 >= valor2} <br>`);